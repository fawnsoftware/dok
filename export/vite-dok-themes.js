import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { readFileSync, writeFileSync } from 'node:fs';
import { load } from 'js-yaml';

const __dirname = dirname(fileURLToPath(import.meta.url));

/**
 * Generates resources/css/themes.css from dok-themes.yaml, so adding
 * or removing a theme only ever requires editing the manifest.
 */
export function dokThemes() {
    const themesDir = resolve(__dirname, 'resources/css');
    const manifestPath = resolve(__dirname, 'dok-themes.yaml');
    const importsPath = resolve(themesDir, 'themes.css');

    const generate = () => {
        const manifest = load(readFileSync(manifestPath, 'utf8'));
        const themes = manifest?.themes ?? [];

        const header = `/*
* ------------------------------------------------------------------
*  This file is auto-generated - do not edit it directly.
* ------------------------------------------------------------------
*
*  Generated by the themeImports() Vite plugin in vite-theme-imports.js,
*  from the theme manifest at dok-themes.yaml.
*
*  It contains one @import per theme listed in the manifest, wiring
*  each theme's CSS file into the build.
*
*  To add, remove, or reorder a theme, edit dok-themes.yaml instead
*  of this file. It regenerates automatically:
*    - on every "vite build"
*    - when the "vite dev" server starts
*    - whenever dok-themes.yaml changes while "vite dev" is running
*
*  Any changes made directly to this file will be overwritten the
*  next time it regenerates.
*/
\n
`;

        const imports = themes
            .map(theme => `@import "./themes/${theme.id}.css";`)
            .join('\n') + '\n';

        writeFileSync(importsPath, header + imports);
    };

    return {
        name: 'theme-imports',
        buildStart() {
            generate();
        },
        configureServer(server) {
            generate();

            server.watcher.add(manifestPath);

            server.watcher.on('change', (file) => {
                if (file === manifestPath) {
                    generate();
                }
            });
        },
    };
}
